/**
 * Build the allowed-tools list for a given mode.
 *
 * The on-disk `<backlogRoot>/allowed-tools.json` is lazily regenerated by
 * `ensureAllowedTools` if its `_generated` header is stale relative to the
 * repo-independent allowlist input (the top-level `{plugins, forge}` plus
 * every repo's `overrides.plugins`; see `allowlistInput`) or the generator
 * version was bumped. Callers pass `config` so the staleness check has the
 * live config to hash against; the legacy `backlogRoot`-only call path is
 * retained for tests/edge cases that still want to read the file as-is.
 *
 * The committed file holds templated plugin leaders
 * (`{{roostDir}}/tools/node_modules/.bin/prettier:*`) so it is the same on
 * every machine. This is the one place they become absolute for Claude and
 * Gemini: `base`, the mode list and the local extras go through
 * `resolveAllowedTokens` with `roostDir` (the argument, else
 * `config.roostDir`) and `backlogRoot`; a token that
 * cannot be resolved is dropped rather than passed through as a dead rule.
 * Codex resolves the same placeholders again in `expandRoostPlaceholders`,
 * harmlessly. `backlog.json` `session_stack.allow` tokens (`config` only,
 * session-stack.js) are resolved the same way after the local extras; they
 * are never written to the file. The worktree's `Bash(rm <worktree>/*)` rule
 * is appended last.
 */
export function getAllowedTools(mode, { backlogRoot, roostDir, worktreePath, config } = {}) {
  if (!backlogRoot) {
    throw new Error('getAllowedTools: backlogRoot is required');
  }
  let toolDefs;
  if (config) {
    toolDefs = ensureAllowedTools(backlogRoot, config);
  } else {
    const path = join(backlogRoot, 'allowed-tools.json');
    if (!existsSync(path)) {
      throw new Error(`Missing ${path}. Run 'bl init' to copy the template from bl/templates/allowed-tools.json.`);
    }
    toolDefs = JSON.parse(readFileSync(path, 'utf8'));
  }
  const r = roostDir ?? config?.roostDir ?? '';
  const dynamic = worktreePath ? [`Bash(rm ${worktreePath}/*)`] : [];
  // A workspace's session-stack grants (S-581); none unless backlog.json
  // names them.
  const stackAllow = config?.topLevel ? sessionStackOf(config.topLevel, backlogRoot).allow : [];
  // User-discretion grants from the gitignored allowed-tools.local.json (what
  // `bl allow` records) — merged in here so they reach the agent without ever
  // being committed to the shared allowed-tools.json.
  const localExtra = loadLocalTools(backlogRoot).extra;
  const resolved = resolveAllowedTokens(
    [...(toolDefs.base ?? []), ...(toolDefs[mode] ?? []), ...localExtra, ...stackAllow],
    { roostDir: r, backlogRoot },
  );
  return [...resolved, ...dynamic];
}

/**
 * Hard-denied tool tokens for a mode (the generated file's `deny` map).
 * Generic tokens like the allowlist's; each provider translates them into
 * its own refusal mechanism (Claude `--disallowedTools`, Gemini policy deny
 * rules, Codex prompt guidance). Denials override the allowlist — see
 * MODE_DENY in allowed-tools.js for what's denied and why.
 */
export function getDeniedTools(mode, { backlogRoot, config } = {}) {
  if (!backlogRoot) {
    throw new Error('getDeniedTools: backlogRoot is required');
  }
  let toolDefs;
  if (config) {
    toolDefs = ensureAllowedTools(backlogRoot, config);
  } else {
    const path = join(backlogRoot, 'allowed-tools.json');
    if (!existsSync(path)) return [];
    toolDefs = JSON.parse(readFileSync(path, 'utf8'));
  }
  return [...(toolDefs.deny?.[mode] ?? [])];
}

/**
 * Template slots filled from a shared fragment in `prompts/`. `blockedByBug`
 * is the "blocked by a bug: fix it, record an ad-hoc story, keep going" rule
 * every code-writing feature prompt carries (story, self-review, review fix,
 * fix self-review, fix-tests, interactive workon). `escalationGuide` is the
 * shape an escalation takes so the operator can decide at a glance (the rule,
 * how it works, the problem, why the agents can't fix it, the decision,
 * details); every prompt that can escalate carries it, the verifier included.
 * `validateBeforeSync` is the backlog commit flow (`bl validate` until clean,
 * then a locked `bl sync --commit`) every story-editing prompt ends with.
 * `sideChangeGuide` is the side-change rule (a change outside your own
 * unit's repos is a story made with `bl side`, never a hand-made worktree or
 * PR) carried by every refine and workon prompt, the feature's story session
 * and the story run; the other loop prompts do not. `selfConsistencyGuide` is
 * the rule that a change derives from what the system already defines rather
 * than restating it, carried by every refine and implementation prompt and by
 * the two prompts that review for it.
 */
const PROMPT_PARTIALS = {
  blockedByBug: '_blocked-by-bug',
  escalationGuide: '_escalation',
  validateBeforeSync: '_validate-before-sync',
  sideChangeGuide: '_side-changes',
  selfConsistencyGuide: '_self-consistency',
};

/**
 * Partials a story run (`bl run S-n`, `vars.unitKind === "story"`) gets in
 * place of the feature's: a story has no feature to attach an ad-hoc story to.
 */
const STORY_PARTIALS = {
  blockedByBug: '_blocked-by-bug-story',
};

/**
 * The unit a side change's `bl side --from` names: the session's feature (a
 * story run's `featureId` is its story), else its story, else a placeholder
 * for a session that has several (`refine-batch`).
 */
function sideFrom(vars) {
  return vars?.featureId || vars?.storyId || '<F-n|S-n>';
}

/**
 * Load a prompt template and interpolate `{{vars}}`.
 *
 * Renders the shared `_tool-guide.md` fragment first against `config` and
 * the agent's tool-name hints, then injects the result as `{{toolGuide}}`
 * so every top-level prompt can drop its inline tool-usage / on-PATH /
 * format / PR blocks in favour of one reference.
 *
 * The third argument accepts either an agent name string (back-compat
 * with pre-S-442 callers) or `{ agent, config }`. When config is omitted
 * the renderer falls back to `_(none configured)_` placeholders so the
 * prompt is still well-formed — that's the mode tests and the no-config
 * code paths land in.
 */
export function loadPrompt(name, vars, agentOrOpts = 'claude') {
  const opts =
    typeof agentOrOpts === 'string'
      ? { agent: agentOrOpts, config: null }
      : { agent: agentOrOpts.agent ?? 'claude', config: agentOrOpts.config };

  const locale = resolveLocale(opts.config);
  const dir = process.env.BL_INTERNAL_TEST_PROMPTS_DIR || join(__dirname, '..', 'prompts');
  let promptPath = join(dir, `${name}.md`);
  for (const variant of fragmentCandidates(name, locale, opts.agent)) {
    const p = join(dir, variant);
    if (existsSync(p)) {
      promptPath = p;
      break;
    }
  }
  let text = readFileSync(promptPath, 'utf8');

  const provider = getProvider(opts.agent);
  const toolHints = provider.getToolHints();
  const toolGuide = renderToolGuide(opts.config, toolHints, vars, opts.agent);
  // Shared partials, rendered only for templates that name their slot, with
  // the same variables as the template (a per-session `scratchDir` included).
  const partials = {};
  for (const [slot, fragment] of Object.entries(PROMPT_PARTIALS)) {
    if (text.includes(`{{${slot}}}`) && vars?.[slot] == null) {
      const fragmentVars = { ...toolHints, ...vars };
      if (slot === 'sideChangeGuide') {
        fragmentVars.sideFrom = sideFrom(vars);
      }
      const name = vars?.unitKind === 'story' ? (STORY_PARTIALS[slot] ?? fragment) : fragment;
      partials[slot] = renderFragment(name, fragmentVars, locale, opts.agent);
    }
  }
  // The workspace's session-stack guidance (S-581): `<guide>/<prompt>.md`,
  // else `<guide>/default.md`; "" when backlog.json names no guide.
  if (text.includes('{{sessionStack}}') && vars?.sessionStack == null) {
    partials.sessionStack = renderSessionStack(opts.config, [name, 'default'], { ...toolHints, ...vars });
  }
  const allVars = { ...toolHints, toolGuide, ...partials, ...vars };

  for (const [k, v] of Object.entries(allVars)) {
    text = text.replaceAll(`{{${k}}}`, v ?? '');
  }
  return text;
}

/**
 * Spill per-sub-agent instruction blocks to individual temp files.
 *
 * Batch orchestrators (`bl refine`/`bl implement` with several stories) used to
 * embed every story's full prompt inline in the orchestrator's own prompt, but
 * that prompt is handed to the agent as a single CLI argument — and a single
 * argv string is capped at ~128 KB on Linux (`MAX_ARG_STRLEN`), so a few
 * tool-guide-laden blocks overflow it (`spawnSync … E2BIG`). Writing each block
 * to its own file keeps the orchestrator prompt tiny (just a list of file
 * pointers) and keeps each sub-agent's read under the Read tool's line cap.
 *
 * Files land under the OS temp dir — never inside the backlog repo, so
 * `bl merge`'s `git add` can't sweep them in. The interactive session may be
 * resumed later, so the dir is intentionally left in place rather than unlinked
 * on spawn exit.
 *
 * @param {string} prefix — short tag for the temp dir name (e.g. "workon")
 * @param {Array<{ id: string, title: string, body: string }>} items
 * @returns {{ dir: string, files: Array<{ id, title, file }> }}
 */
export function spillSubagentPrompts(prefix, items) {
  const dir = mkdtempSync(join(tmpdir(), `bl-${prefix}-`));
  const files = items.map((it) => {
    const file = join(dir, `${it.id}.md`);
    writeFileSync(file, it.body);
    return { id: it.id, title: it.title, file };
  });
  return { dir, files };
}

/**
 * Prepend the `_pre-task-discussion.md` preamble to `sessionPrompt` when
 * `additionalPrompt` is a non-empty string. Otherwise return `sessionPrompt`
 * unchanged. Extracted from `launchSession` so the preamble shape can be
 * unit-tested without spawning a provider.
 */
export function applyAdditionalPrompt(
  sessionPrompt,
  additionalPrompt,
  { mode, storyId, agent = 'claude', config = null } = {},
) {
  if (typeof additionalPrompt !== 'string' || additionalPrompt.length === 0) {
    return sessionPrompt;
  }
  const preamble = loadPrompt(
    '_pre-task-discussion',
    // The `workon` permission mode is the `bl implement` verb.
    { additionalPrompt, mode: mode === 'workon' ? 'implement' : mode, storyId },
    { agent, config },
  );
  return preamble + (sessionPrompt ?? '');
}

/**
 * The guards a new worktree in `repoPath` passes first: the main checkout
 * has no uncommitted changes, and, when it is on main, main is synced
 * without being ahead of origin. Exits 1 naming the problem. `bl side` runs
 * them before it writes anything (F-48 D1).
 * @param {string} repoPath — absolute path to the code repo's main checkout
 */
export function newWorktreeGuards(repoPath) {
  const currentBranch = execSync('git rev-parse --abbrev-ref HEAD', {
    cwd: repoPath,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();

  const status = execSync('git status --porcelain', {
    cwd: repoPath,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
  if (status) {
    console.error(`Error: ${repoPath} has uncommitted changes. They will NOT be in the worktree.`);
    console.error('Commit or stash before starting a new story.\n');
    process.exit(1);
  }

  if (currentBranch === 'main') {
    // Fetch, ahead-of-origin check and fast-forward run under the per-repo
    // lock, so sibling `bl run` children on one repo take turns (S-865).
    // A failed fetch is a warning (the worktree is cut from local main);
    // a failed fast-forward, a lock timeout or an unpushed main stops here.
    info('Pulling latest main...');
    if (!reportMainSync(syncMain(repoPath, { checkAhead: true }), repoPath)) {
      process.exit(1);
    }
    info('');
  }
}

/** `path` with its links resolved, or resolved as given when it is not there. */
function realOrResolved(path) {
  try {
    return realpathSync(path);
  } catch {
    return resolve(path);
  }
}

/**
 * Ensure the worktree exists and main is up-to-date in the given repo.
 * A branch already checked out anywhere but `worktreePath` is refused (exit
 * 1), not reused: the session starts in, and writes to, the unit directory
 * only (F-60 D3).
 * @param {string} repoPath — absolute path to the code repo to create the worktree in
 * @param {string} branchName
 * @param {string} worktreePath — desired absolute worktree path
 */
export function ensureWorktree(repoPath, branchName, worktreePath) {
  const existingWorktree = findExistingWorktree(repoPath, branchName);
  const isNewWorktree = existingWorktree == null;

  if (existingWorktree && realOrResolved(existingWorktree.path) !== realOrResolved(worktreePath)) {
    console.error(
      `Error: branch '${branchName}' is checked out at ${existingWorktree.path}, outside its unit directory ${dirname(worktreePath)}.`,
    );
    console.error(`Move it there first: git -C ${repoPath} worktree move ${existingWorktree.path} ${worktreePath}\n`);
    process.exit(1);
  }

  if (isNewWorktree) {
    newWorktreeGuards(repoPath);

    const branchExists = (() => {
      try {
        execSync(`git rev-parse --verify "${branchName}"`, {
          cwd: repoPath,
          stdio: ['ignore', 'pipe', 'pipe'],
        });
        return true;
      } catch {
        return false;
      }
    })();

    // git-crypt keys live in the main gitdir under git-crypt/keys/. A linked
    // worktree has its own gitdir, so the smudge filter fails on checkout
    // unless we link the keys into the worktree's gitdir first.
    const mainGitCrypt = join(repoPath, '.git', 'git-crypt');
    const usesGitCrypt = existsSync(join(mainGitCrypt, 'keys', 'default'));

    if (branchExists) {
      info(`Creating worktree from existing branch '${branchName}'...`);
      execSync(`git worktree add --no-checkout "${worktreePath}" "${branchName}"`, {
        cwd: repoPath,
        stdio: ['inherit', process.stderr, process.stderr],
      });
    } else {
      info(`Creating new worktree + branch '${branchName}' from main...`);
      execSync(`git worktree add --no-checkout -b "${branchName}" "${worktreePath}" main`, {
        cwd: repoPath,
        stdio: ['inherit', process.stderr, process.stderr],
      });
    }

    if (usesGitCrypt) {
      const worktreeGitDir = execSync('git rev-parse --absolute-git-dir', {
        cwd: worktreePath,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
      }).trim();
      const linkPath = join(worktreeGitDir, 'git-crypt');
      if (!existsSync(linkPath)) {
        symlinkSync(mainGitCrypt, linkPath);
      }
    }

    execSync('git checkout', {
      cwd: worktreePath,
      stdio: ['inherit', process.stderr, process.stderr],
    });
    info('');
  } else {
    info(`Worktree already exists at ${existingWorktree.path}`);
    if (isSessionRunning(unitDirOf(worktreePath))) {
      console.error('\nWarning: a session lock exists in the unit directory.');
      console.error('Another agent session may be running. Proceeding anyway,');
      console.error('but be aware of conflicts if two sessions edit the same files.\n');
    }
  }

  return {
    effectiveWorktreePath: existingWorktree?.path ?? worktreePath,
    isNewWorktree,
  };
}

/**
 * Bootstrap the worktree(s) for a story by running the `bootstrap` stage
 * plugin resolved through the standard frontmatter cascade.
 *
 * Story ID is the canonical scope: the story's one repo, its component's
 * (`reposForStory`, F-52 D1), has its worktree bootstrapped with its resolved
 * plugin. Node repos register `plugins-bootstrap: ["node-ws"]` on their
 * `backlog.json` `repos` entry and get `pnpm install`; Go repos get
 * `go mod download`; etc. A worktree that doesn't yet exist on disk is
 * skipped.
 *
 * `repoName` limits the loop to that one repo (a story worktree prepared on
 * its own, S-862); `worktreePath` is then where that worktree really is,
 * which differs from the convention when the branch was already checked out
 * elsewhere.
 *
 * Missing-binary or non-zero exits are logged and never exit here: we'd
 * rather launch the agent and let the user fix tooling than block the
 * session. Returns false when a bootstrap plugin failed, so a caller that
 * must not go on without it (a headless run) can stop.
 *
 * @returns {boolean}
 */
export function installDeps(config, parsed, { componentEntry, storyEntry, repoName = null, worktreePath = null } = {}) {
  // `bl implement` always passes a parsed story; the no-story path is unreachable
  // from production callers. Keep the invariant loud so a future refactor
  // that breaks it surfaces immediately rather than silently no-op'ing.
  assert(parsed?.id, 'installDeps: parsed.id is required');
  const repos = reposForStory(parsed.id, config)
    .filter((r) => repoName == null || r.repoName === repoName)
    .map((r) => (repoName != null && worktreePath ? { ...r, worktreePath } : r));
  if (repos.length === 0) {
    info('  (bootstrap skipped — story has no repos resolved)');
    info('');
    return true;
  }

  let ok = true;
  for (const r of repos) {
    if (!existsSync(r.worktreePath)) continue;
    // The story's repo layer (its component's repo), whatever repo `config`
    // is for (F-51 D4).
    const activePlugins = resolvePlugins('bootstrap', config.plugins, {
      backlogRoot: config.backlogRoot,
      repo: config.repos?.[r.unitRepo] ?? null,
      componentEntry: componentEntry ?? r.componentEntry,
      storyEntry: storyEntry ?? r.storyEntry,
    });
    if (activePlugins.length === 0) {
      // The previous `pnpm install` default ran for everyone; with the
      // plugin-stage rework, repos with no `plugins-bootstrap` cascade
      // entry get nothing. Surface that so users upgrading bl notice they
      // need to opt in (or explicitly accept the no-op via `-name` in their
      // frontmatter cascade).
      info(
        `  (no bootstrap plugin configured for ${r.repoName} — set "plugins-bootstrap" on its backlog.json repos entry, or 'plugins-bootstrap: <name>' in the component or story frontmatter, to opt in)`,
      );
      continue;
    }

    info(`Bootstrapping ${r.repoName} worktree...`);
    const pluginVars = {
      sessionId: `s${parsed.num}`,
      storyId: parsed.id,
      worktreePath: r.worktreePath,
      repoPath: r.repoPath,
      repoName: r.repoName,
      backlogDir: config.backlogRoot,
      roostDir: config.roostDir,
    };
    if (!runPlugins(activePlugins, pluginVars, r.worktreePath)) {
      ok = false;
      info(`  (${r.repoName} bootstrap failed — you may need to run it manually)`);
    }
    info('');
  }
  return ok;
}

/** The marker in a worktree's own git dir that its `workon` plugins are owed. */
function workonMarker(worktreePath) {
  const gitDir = execSync('git rev-parse --absolute-git-dir', {
    cwd: worktreePath,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
  return join(gitDir, 'bl-workon-pending');
}

/**
 * Whether a worktree still owes its `workon` stage plugins (S-862): a new
 * worktree does, and so does one whose earlier run of them failed, so a retry
 * runs them again instead of taking the existing worktree as done. The debt
 * lives in the worktree's git dir, out of the working tree; `workonDone`
 * clears it.
 */
export function workonDue(worktreePath, isNewWorktree) {
  const marker = workonMarker(worktreePath);
  if (isNewWorktree) writeFileSync(marker, '');
  return existsSync(marker);
}

/** Clear a worktree's `workon` debt once its plugins have succeeded. */
export function workonDone(worktreePath) {
  const marker = workonMarker(worktreePath);
  if (existsSync(marker)) unlinkSync(marker);
}

/**
 * Run `fn` (making a worktree and running its bootstrap and `workon` plugins)
 * as the only preparer of `branchName`'s worktree in `repoPath` (S-862): a
 * concurrent `bl run` or `bl implement` waits here, then finds the worktree
 * made and its `workon` debt paid, or still owed if this one failed. The lock
 * sits in the repo's common git dir, since the worktree may not exist yet; a
 * preparer that exits holding it leaves a lock the next one reclaims.
 */
export function prepareWorktreeOnce(repoPath, branchName, fn) {
  const commonDir = execSync('git rev-parse --path-format=absolute --git-common-dir', {
    cwd: repoPath,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
  const lockPath = join(commonDir, `bl-prepare-${branchName.replace(/[^\w.-]/g, '_')}.lock`);
  const content = `${process.pid}\n${new Date().toISOString()}\nprepare ${branchName}\n`;
  let waiting = false;
  for (;;) {
    const taken = acquirePidLock(lockPath, content);
    if (taken.content) break;
    if (!waiting) info(`Waiting for pid ${taken.holder} to finish preparing ${branchName} in ${repoPath}...`);
    waiting = true;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100);
  }
  try {
    return fn();
  } finally {
    releasePidLock(lockPath, content);
  }
}

/**
 * Run stage plugins if this is a new worktree. Returns false when a plugin
 * failed (the caller decides whether that stops it).
 *
 * @returns {boolean}
 */
export function runStagePlugins(
  stage,
  isNewWorktree,
  config,
  { componentEntry, storyEntry, parsed, worktreePath, branchName, storyRelPath, repoPath },
) {
  if (!isNewWorktree) return true;
  const activePlugins = resolvePlugins(stage, config.plugins, {
    backlogRoot: config.backlogRoot,
    repo: repoOf(config),
    componentEntry,
    storyEntry,
  });
  if (activePlugins.length === 0) return true;

  info(`Running ${stage} plugins...`);
  const pluginVars = {
    sessionId: `s${parsed.num}`,
    storyId: parsed.id,
    worktreePath,
    branchName,
    storyRelPath,
    componentId: componentEntry.replace(/-.*/, ''),
    repoPath,
    roostDir: config.roostDir,
    backlogDir: config.backlogRoot,
  };
  const ok = runPlugins(activePlugins, pluginVars, repoPath);
  if (!ok) console.error(`${stage} plugin failed.\n`);
  info('');
  return ok;
}

/** PID on the first line of a lock file, or null when absent/unreadable. */
function lockHolderPid(lockPath) {
  try {
    const pid = parseInt(readFileSync(lockPath, 'utf8').split('\n', 1)[0], 10);
    return Number.isInteger(pid) && pid > 0 ? pid : null;
  } catch {
    return null;
  }
}

/**
 * Appended to every headless prompt. A `claude -p` / `codex exec` session ends
 * the moment the agent stops: on F-4 a self-review started the full test suite
 * in the background, said it would wait, and ended with nothing checked; a fix
 * self-review edited four files and never committed them, failing the next
 * test gate. Nothing in a headless run resumes an agent, so it must hear that.
 *
 * @param {string} prompt
 * @param {string} mode  `workon` sessions also change code and must commit it.
 */
export function withHeadlessRules(prompt, mode) {
  const commit =
    mode === 'workon'
      ? "\n- Commit every change you make before you end. A modified or untracked file left in the\n  worktree fails the loop's clean-tree test gate.\n"
      : '\n';
  return `${String(prompt).replace(/\n+$/, '')}

## This session is headless

Nobody is watching and nothing resumes you: the session ends the moment you stop, and anything
still running in the background is killed with it.

- Run every command in the foreground and wait for its result. Never start a command in the
  background, and never end a reply by saying you will wait for something.
- Keep each command under ten minutes. The loop runs the full test suite in its test gate after
  this session, so where your instructions say to run the full suite, run the tests that cover
  what you changed instead.${commit}`;
}

/**
 * The model a session of `agent` runs on (F-64 D2). A caller that names one
 * (null: none) gets it: the configuration's own model, which `bl run` passes
 * for every step. A caller that names none gets the first implementing
 * configuration's model when `agent` is that configuration's agent, and no
 * model otherwise, so one agent's model never reaches another's `--model`
 * or `-m`.
 */
function sessionModel(model, agent, config) {
  if (model !== undefined) return model == null ? null : checkModel(model, 'model');
  return config?.agent === agent ? (config.agentModel ?? null) : null;
}

/**
 * Run one prompt to completion without a terminal and return what the agent
 * said. The building block of `bl run`: same allowlist, deny list,
 * and directory scopes as `launchSession`, but no session name, no resume,
 * no tmux rename, and the result comes back to the caller instead of the
 * screen. Usage is accumulated on `usageIndexPath` (the feature file) when
 * given, and with `usageStep` into its `tokens_by_step[usageStep]` as well.
 *
 * The agent starts in `unitDir`, the unit directory (F-60 D3), which is also
 * its write root and holds the session lock; `worktreePath` is the lead
 * repo's worktree, for the activity log. Without `unitDir` (a caller with no
 * unit) both are `worktreePath`.
 *
 * @returns {{ status: number, output: string, isError: boolean,
 *             usage: object|null, sessionId: string|null, denials: string[],
 *             refusal?: object|null, error?: string }}
 */
export function runHeadlessSession({
  mode,
  parsed,
  prompt,
  worktreePath,
  unitDir = null,
  agent = 'claude',
  config = null,
  roostDir,
  backlogRoot,
  label = null,
  usageIndexPath = null,
  usageStep = null,
  logCommand = null,
  model = null,
  run = undefined,
  provider: providerOverride = null,
}) {
  // `provider` is a test seam; production resolves it from `agent`. `run`,
  // when given, replaces the adapter's `spawnSync` for the agent itself: `bl
  // run` passes one that starts it in a user systemd scope (F-70 D4).
  const provider = providerOverride ?? getProvider(agent);
  const cwd = unitDir ?? worktreePath;
  if (typeof provider.supportsHeadless !== 'function' || !provider.supportsHeadless()) {
    return {
      status: 1,
      output: '',
      isError: true,
      usage: null,
      sessionId: null,
      denials: [],
      error: `agent provider '${agent}' has no headless mode`,
    };
  }

  // Never take over a live session's lock: overwriting it and unlinking it
  // afterwards would hide that session from `bl merge`'s guard. A lock this
  // process already holds is left as it is; a stale one is reclaimed, taken
  // exclusively (see pid-lock.js) so two reclaimers cannot both win.
  const lockPath = join(cwd, LOCK_FILE);
  let lockContent = null;
  if (lockHolderPid(lockPath) !== process.pid) {
    let taken;
    try {
      taken = acquirePidLock(
        lockPath,
        `${process.pid}\n${new Date().toISOString()}\n${label ?? parsed.id} (headless)\n`,
      );
    } catch {
      taken = {}; // an unwritable lock is non-fatal
    }
    if (taken.holder != null && taken.holder !== process.pid) {
      return {
        status: 1,
        output: '',
        isError: true,
        usage: null,
        sessionId: null,
        denials: [],
        error: `a live session (pid ${taken.holder}) holds ${lockPath}`,
      };
    }
    lockContent = taken.content ?? null;
  }
  try {
    logAppendTo(worktreePath, logCommand ?? mode, [parsed.id, '--headless']);
  } catch {
    // logging is non-fatal
  }

  const allowedTools = getAllowedTools(mode, {
    backlogRoot,
    roostDir,
    worktreePath: cwd,
    config,
  });
  const deniedTools = getDeniedTools(mode, { backlogRoot, config });
  const translatedPermissions = provider.translatePermissions(allowedTools, {
    mode,
    roostDir,
    backlogRoot,
    worktreePath,
    unitDir: cwd,
    worktreeRoot: config ? worktreeRoot(config) : null,
  });
  const scopes = resolvePermissionScopes(config, { unitDir: cwd });

  let result;
  try {
    result = provider.spawn({
      mode,
      name: label,
      prompt: withHeadlessRules(prompt, mode),
      permissions: translatedPermissions,
      denied: deniedTools,
      worktreePath,
      cwd,
      sessionId: null,
      roostDir,
      backlogRoot,
      scopes,
      headless: true,
      // The configuration's own model, which the walk always passes (F-64
      // D3); no implementing default, so a review never runs on it.
      model: model == null ? null : checkModel(model, 'model'),
      ...(run ? { run } : {}),
    });
  } finally {
    // Only the lock this call wrote, and only while it is still ours.
    try {
      if (lockContent != null && readFileSync(lockPath, 'utf8') === lockContent) unlinkSync(lockPath);
    } catch {
      // already gone
    }
  }

  if (result?.error) {
    return {
      status: 1,
      output: '',
      isError: true,
      usage: null,
      sessionId: null,
      denials: [],
      error: result.error.message ?? String(result.error),
    };
  }
  // A killed agent (`signal`, `status: null`) is 128 + n, so it is an
  // error whatever its output said (F-70 D3).
  const status = exitStatus(result);
  const out = {
    status,
    output: result?.output ?? '',
    isError: result?.isError === true || status !== 0,
    usage: result?.usage ?? null,
    sessionId: result?.sessionId ?? null,
    denials: Array.isArray(result?.denials) ? result.denials : [],
    // A refusal the adapter recognised (its `refusal`, provider.js
    // `supportsHeadless`); the loop waits it out instead of counting the
    // session as an attempt.
    refusal: result?.refusal ?? null,
  };
  if (usageIndexPath && out.usage) accumulateTokensOnFile(backlogRoot, usageIndexPath, out.usage, usageStep);
  return out;
}

/**
 * Launch an agent session (or resume an existing one).
 *
 * `sessionName` / `tmuxLabel` override the story-derived display strings (used
 * by the batch-refine orchestrator, which fans out to per-story sub-agents and
 * therefore has no single owning story). `recordTokens: false` skips the
 * post-session token bookkeeping for the same reason.
 *
 * With `tokensStep` and `tokensIndexPath`, the difference between the
 * provider's transcript totals for this worktree before and after the session
 * goes into `tokens_by_step[tokensStep]` on `tokensIndexPath` (S-904), and
 * into its totals in the same write, whether the session succeeded, failed
 * or threw: a re-read cannot say which session a transcript line belongs to.
 *
 * As in `runHeadlessSession`, the agent starts in `unitDir` when given, its
 * write root and lock directory, and its transcripts are found there.
 */
export function launchSession({
  mode,
  parsed,
  title,
  worktreePath,
  unitDir = null,
  branchName,
  sessionPrompt,
  roostDir,
  backlogRoot,
  isNewWorktree,
  agent = 'claude',
  forceNew = false,
  config = null,
  additionalPrompt,
  returnOnExit = false,
  sessionName: sessionNameOverride = null,
  tmuxLabel: tmuxLabelOverride = null,
  recordTokens = true,
  tokensStep = null,
  tokensIndexPath = null,
  model = undefined,
  provider: providerOverride = null,
}) {
  const isRefine = mode === 'refine';
  const sessionName = sessionNameOverride ?? (isRefine ? `${parsed.id}: refine — ${title}` : `${parsed.id}: ${title}`);

  // `provider` is a test seam; production resolves it from `agent`.
  const provider = providerOverride ?? getProvider(agent);
  const cwd = unitDir ?? worktreePath;
  const shouldResume = !isNewWorktree && !forceNew;
  const existingSessionId = shouldResume ? provider.findSession(cwd, sessionName) : null;

  if (existingSessionId) {
    info(`Found existing session for ${parsed.id} — will resume.\n`);
  } else if (shouldResume) {
    info(`Worktree exists but no previous session found — starting fresh.\n`);
  }

  const tmuxLabel = tmuxLabelOverride ?? (isRefine ? `${parsed.id} refine` : parsed.id);
  renameTmuxWindow(tmuxLabel);

  // A lock this process already holds (a feature's `bl review` round holds every
  // unit directory's for the whole round) is neither rewritten nor released here.
  const lockPath = join(cwd, LOCK_FILE);
  const takeLock = lockHolderPid(lockPath) !== process.pid;
  try {
    if (takeLock) {
      writeFileSync(lockPath, `${process.pid}\n${new Date().toISOString()}\n${sessionName}\n`);
    }
  } catch {
    // non-fatal
  }
  // The `finally` below releases the lock this call took. The exit listener
  // is a belt-and-braces guard for the terminal case where the process exits
  // without unwinding the spawn frame. Skip it in `returnOnExit` mode — the
  // multi-PR loop calls this repeatedly, and accumulated listeners would trip
  // MaxListenersExceededWarning past 10 PRs.
  if (takeLock && !returnOnExit) {
    process.on('exit', () => {
      try {
        unlinkSync(lockPath);
      } catch {
        // already gone
      }
    });
  }

  const blCommand = isRefine ? 'refine' : 'workon';
  logAppendTo(worktreePath, blCommand, [parsed.id]);

  const allowedTools = getAllowedTools(mode, {
    backlogRoot,
    roostDir,
    worktreePath: cwd,
    config,
  });
  // Generic deny tokens ride along untranslated — each provider renders them
  // into its own refusal mechanism inside spawn (codex's translatePermissions
  // returns an object, so a shared pre-translation here can't work).
  const deniedTools = getDeniedTools(mode, { backlogRoot, config });

  const translatedPermissions = provider.translatePermissions(allowedTools, {
    mode,
    roostDir,
    backlogRoot,
    worktreePath,
    unitDir: cwd,
    worktreeRoot: config ? worktreeRoot(config) : null,
  });
  const scopes = resolvePermissionScopes(config, { unitDir: cwd });

  const effectivePrompt = applyAdditionalPrompt(sessionPrompt, additionalPrompt, {
    mode,
    storyId: parsed.id,
    agent,
    config,
  });

  // The transcript totals before the session, for its per-step difference.
  // `undefined` when they could not be read: then nothing is recorded.
  let tokensBefore;
  if (tokensStep && tokensIndexPath) {
    try {
      tokensBefore = sessionTokens(provider, cwd, parsed.id);
    } catch {
      // bookkeeping must never block the session
    }
  }

  let result;
  try {
    result = provider.spawn({
      mode,
      name: sessionName,
      prompt: effectivePrompt,
      permissions: translatedPermissions,
      denied: deniedTools,
      worktreePath,
      cwd,
      sessionId: existingSessionId,
      roostDir,
      backlogRoot,
      scopes,
      model: sessionModel(model, agent, config),
    });
  } finally {
    try {
      if (takeLock) unlinkSync(lockPath);
    } catch {
      // already gone
    }
    // Here, so a spawn that throws or fails still records what its session
    // used, step and totals in one write; before `recordStoryTokens`, which
    // re-reads the file this writes.
    if (tokensBefore !== undefined) {
      try {
        const delta = usageDelta(tokensBefore, sessionTokens(provider, cwd, parsed.id));
        accumulateStepTokensOnFile(backlogRoot, tokensIndexPath, tokensStep, delta);
      } catch {
        // bookkeeping must never block exit
      }
    }
  }

  if (result.error) {
    console.error(`Error: failed to launch agent '${agent}': ${result.error.message}`);
    if (returnOnExit) return 1;
    process.exit(1);
  }

  // Recompute token totals from the just-finished session and write them to
  // the story's frontmatter. Idempotent: the next launch will recompute and
  // overwrite, so a hard kill here is recovered automatically. Skipped for
  // sessions that don't map to a single story (e.g. a batch-refine orchestrator).
  if (recordTokens) {
    try {
      recordStoryTokens(parsed.id, { ...config, agent, backlogRoot, roostDir });
    } catch {
      // bookkeeping must never block exit
    }
  }

  const status = exitStatus(result);
  if (returnOnExit) return status;
  process.exit(status);
}
